import { mkdir, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { chromium } from 'playwright';
import { createServer } from 'vite';

const root = resolve(import.meta.dirname, '..');
const output = resolve(root, 'artifacts', 'skills-redesign');
if (!process.argv[2]) throw new Error('Pass a local portfolio_content.json snapshot path. No production writes are made.');
const snapshot = JSON.parse(await readFile(resolve(process.argv[2]), 'utf8'))[0].content;
const baseUrl = 'http://127.0.0.1:5195';
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const group = (index, skills) => ({ id: `test-group-${index}`, name: index === 5 ? 'An intentionally longer technical discipline heading' : `Skill Group ${index}`, description: index === 5 ? 'A longer group description that should wrap naturally without clipping or pushing into adjacent cards.' : '', skills: Array.from({ length: skills }, (_, item) => ({ id: `test-skill-${index}-${item}`, name: item === 0 && index === 5 ? 'A very long skill name that must remain visible on a narrow screen' : `Skill ${index}.${item}` })) });
const fixtures = [1, 2, 3, 4, 5, 8].map(count => ({ count, content: { ...snapshot, skillGroups: Array.from({ length: count }, (_, index) => group(index + 1, index === 2 ? 0 : index === 4 ? 7 : 3)) } }));
await mkdir(output, { recursive: true });
const server = await createServer({ root, server: { host: '127.0.0.1', port: 5195, strictPort: true } });
await server.listen();
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const results = [];
try {
  for (const width of [1920, 1440, 1024, 768, 390]) {
    for (const fixture of fixtures) {
      const context = await browser.newContext({ viewport: { width, height: width === 390 ? 844 : 1000 }, isMobile: width === 390, hasTouch: width === 390, reducedMotion: 'reduce' });
      await context.route('**/rest/v1/portfolio_content*', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ id: 'skills-local-fixture', content: fixture.content }) }));
      const page = await context.newPage();
      const errors = [];
      page.on('pageerror', error => errors.push(error.message));
      await page.goto(baseUrl, { waitUntil: 'domcontentloaded' });
      await page.locator('#skills .skill-group').first().waitFor();
      await page.locator('#skills').scrollIntoViewIfNeeded();
      const geometry = await page.evaluate(() => {
        const groups = [...document.querySelectorAll('#skills .skill-group')];
        const rect = element => element.getBoundingClientRect();
        return { overflow: document.documentElement.scrollWidth - innerWidth, groups: groups.map(group => {
          const card = rect(group.querySelector('article'));
          const title = rect(group.querySelector('h3'));
          const list = rect(group.querySelector('.skill-items'));
          return { cardLeft: card.left, cardRight: card.right, titleRight: title.right, titleBottom: title.bottom, listLeft: list.left, listTop: list.top, itemCount: group.querySelectorAll('.skill-items > li:not(.skill-empty)').length };
        }) };
      });
      assert(geometry.groups.length === fixture.count, `${width}/${fixture.count}: wrong group count`);
      assert(geometry.overflow <= 2, `${width}/${fixture.count}: horizontal overflow ${geometry.overflow}`);
      assert(geometry.groups.every(item => item.cardLeft >= -2 && item.cardRight <= width + 2 && (item.titleRight <= item.listLeft + 2 || item.titleBottom <= item.listTop + 2)), `${width}/${fixture.count}: title/list collision`);
      assert(geometry.groups.every((item, index) => item.itemCount === fixture.content.skillGroups[index].skills.length), `${width}/${fixture.count}: lost skills`);
      assert(errors.length === 0, `${width}/${fixture.count}: ${errors.join(' | ')}`);
      if ((width === 1440 || width === 390) && fixture.count === 5) await page.screenshot({ path: resolve(output, `visitor-${width}.png`) });
      results.push({ width, groups: fixture.count, status: 'PASS' });
      await context.close();
    }
  }

  let saved = null;
  let saveCount = 0;
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.route('**/api/host/session', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ authenticated: true }) }));
  await context.route('**/api/content', route => { saved = JSON.parse(route.request().postData()).content; saveCount += 1; return route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ id: 'skills-local-fixture' }) }); });
  await context.route('**/rest/v1/portfolio_content*', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ id: 'skills-local-fixture', content: saved || fixtures[1].content }) }));
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(baseUrl, { waitUntil: 'domcontentloaded' });
  await page.locator('body.host-mode-active').waitFor();
  const skills = page.locator('#skills');
  await skills.scrollIntoViewIfNeeded();
  await page.screenshot({ path: resolve(output, 'host-1440.png') });
  const originalCount = await skills.locator('.skill-group').count();
  await skills.getByRole('button', { name: '+ Add Skill Group' }).click();
  assert(await skills.locator('.skill-group').count() === originalCount + 1, 'Host add group');
  let newGroup = skills.locator('.skill-group').last();
  const newGroupId = await newGroup.getAttribute('data-skill-group-id');
  await newGroup.locator('h3 .editable-inline').click();
  await newGroup.locator('h3 [contenteditable="true"]').fill('New Technical Field');
  await newGroup.locator('h3 [contenteditable="true"]').blur();
  await newGroup.getByRole('button', { name: '+ Add Skill' }).click();
  assert(await newGroup.locator('.skill-items > li:not(.skill-empty)').count() === 1, 'Host add skill');
  await newGroup.locator('.skill-items .editable-inline').click();
  await newGroup.locator('.skill-items [contenteditable="true"]').fill('Fixture Skill');
  await newGroup.locator('.skill-items [contenteditable="true"]').blur();
  await newGroup.getByRole('combobox', { name: 'Move Fixture Skill to another group' }).selectOption('test-group-1');
  assert(await newGroup.locator('.skill-items > li:not(.skill-empty)').count() === 0, 'Host move skill between groups');
  assert(await skills.locator('.skill-group').first().getByText('Fixture Skill').count() === 1, 'Target group did not receive skill');
  await page.getByRole('button', { name: 'Undo', exact: true }).first().click();
  assert(await newGroup.getByText('Fixture Skill').count() === 1, 'Undo did not restore skill move');
  await page.getByRole('button', { name: 'Redo', exact: true }).first().click();
  assert(await skills.locator('.skill-group').first().getByText('Fixture Skill').count() === 1, 'Redo did not reapply skill move');
  await newGroup.getByRole('button', { name: 'Move up', exact: true }).click();
  assert(await skills.locator('.skill-group').nth(0).getAttribute('data-skill-group-id') === 'test-group-1', 'Group reorder changed wrong end');
  await page.getByRole('button', { name: 'Save', exact: true }).first().click();
  assert(saveCount === 1 && saved.skillGroups.length === originalCount + 1, 'Save did not persist Skills fixture');
  await page.reload();
  await page.locator('body.host-mode-active').waitFor();
  await skills.locator(`[data-skill-group-id="${newGroupId}"] h3`).getByText('New Technical Field').waitFor();
  assert(await skills.locator(`[data-skill-group-id="${newGroupId}"] h3`).getByText('New Technical Field').count() === 1, 'Saved group did not survive refresh');
  await page.getByRole('button', { name: 'Preview', exact: true }).click();
  await page.locator('body.host-preview-active').waitFor();
  await page.screenshot({ path: resolve(output, 'preview-1440.png') });
  assert(await skills.getByText('New Technical Field').count() === 1 && await skills.locator('.inline-record-actions').count() === 0, 'Preview is not visitor-facing');
  await page.getByRole('button', { name: 'Exit Preview' }).click();
  await page.locator('body.host-mode-active').waitFor();
  const firstGroup = skills.locator('[data-skill-group-id="test-group-1"]');
  const movedSkill = firstGroup.locator('.skill-items > li').filter({ hasText: 'Fixture Skill' });
  await movedSkill.getByRole('button', { name: 'Move Fixture Skill up' }).click();
  assert((await firstGroup.locator('.skill-items > li').nth(2).innerText()).includes('Fixture Skill'), 'Move skill up failed');
  await firstGroup.locator('.skill-items > li').nth(2).getByRole('button', { name: 'Move Fixture Skill down' }).click();
  assert((await firstGroup.locator('.skill-items > li').nth(3).innerText()).includes('Fixture Skill'), 'Move skill down failed');
  page.once('dialog', dialog => dialog.accept());
  await movedSkill.getByRole('button', { name: 'Delete Fixture Skill' }).click();
  assert(await movedSkill.count() === 0, 'Delete skill failed');
  await page.getByRole('button', { name: 'Discard', exact: true }).first().click();
  await page.getByRole('dialog', { name: 'Confirm discard' }).getByRole('button', { name: 'Discard' }).click();
  assert(await movedSkill.count() === 1, 'Discard did not restore saved skill');
  newGroup = skills.locator(`[data-skill-group-id="${newGroupId}"]`);
  await newGroup.getByRole('button', { name: 'Manage / delete group' }).click();
  assert(await page.locator('.cms-drawer').count() === 1, 'Manage group did not open inspector');
  const studioGroup = page.locator('.cms-drawer').locator(`[data-skill-group-id="${newGroupId}"]`);
  await studioGroup.getByRole('button', { name: 'Delete group' }).click();
  await studioGroup.getByRole('button', { name: 'Delete', exact: true }).click();
  assert(await skills.locator(`[data-skill-group-id="${newGroupId}"]`).count() === 0, 'Delete group failed');
  await page.getByRole('button', { name: 'Undo', exact: true }).first().click();
  assert(await skills.locator(`[data-skill-group-id="${newGroupId}"]`).count() === 1, 'Undo did not restore deleted group');
  await page.locator('.cms-drawer').getByRole('button', { name: 'Close ×' }).click();
  assert(errors.length === 0, `Host browser errors: ${errors.join(' | ')}`);
  results.push({ host: 'PASS', saveCount, productionWrites: 0 });
  await context.close();
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await mobileContext.route('**/api/host/session', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ authenticated: true }) }));
  await mobileContext.route('**/rest/v1/portfolio_content*', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ id: 'skills-local-fixture', content: fixtures[1].content }) }));
  const mobile = await mobileContext.newPage();
  const mobileErrors = [];
  mobile.on('pageerror', error => mobileErrors.push(error.message));
  await mobile.goto(baseUrl, { waitUntil: 'domcontentloaded' });
  await mobile.locator('body.host-mode-active').waitFor();
  await mobile.locator('#skills .skill-group').first().scrollIntoViewIfNeeded();
  await mobile.screenshot({ path: resolve(output, 'host-390.png') });
  await mobile.locator('#skills .skill-group').first().getByRole('button', { name: '+ Add Skill' }).click();
  assert(await mobile.locator('#skills .skill-group').first().locator('.skill-items > li:not(.skill-empty)').count() === 4, 'Mobile Host add skill failed');
  const mobileOverflow = await mobile.evaluate(() => document.documentElement.scrollWidth - innerWidth);
  assert(mobileOverflow <= 2 && mobileErrors.length === 0, `Mobile Host overflow/errors: ${mobileOverflow}, ${mobileErrors.join(' | ')}`);
  results.push({ mobileHost: 'PASS', overflow: mobileOverflow, productionWrites: 0 });
  await mobileContext.close();
  console.log(JSON.stringify(results, null, 2));
} finally {
  await browser.close();
  await server.close();
}
